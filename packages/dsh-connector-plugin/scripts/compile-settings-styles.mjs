/* global console, process */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(packageRoot, "src/client/settings.generated.ts");
const check = process.argv.includes("--check");
const previous = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";

function unwrapLayers(css) {
  let result = "";
  let cursor = 0;
  while (cursor < css.length) {
    const layerAt = css.indexOf("@layer ", cursor);
    if (layerAt === -1) {
      result += css.slice(cursor);
      break;
    }
    result += css.slice(cursor, layerAt);
    const open = css.indexOf("{", layerAt);
    let depth = 0;
    let end = open;
    for (; end < css.length; end += 1) {
      const char = css[end];
      if (char === "{") depth += 1;
      else if (char === "}") {
        depth -= 1;
        if (depth === 0) {
          end += 1;
          break;
        }
      }
    }
    result += css.slice(open + 1, end - 1);
    cursor = end;
  }
  return result;
}

function scopeToSettings(css) {
  return css
    .replaceAll("*,:before,:after,::backdrop", ".dsh-connector-settings")
    .replaceAll(":root,:host", ".dsh-connector-settings");
}

const builtDir = mkdtempSync(resolve(tmpdir(), "dsh-connector-settings-"));
const builtPath = resolve(builtDir, "settings.css");
try {
  execFileSync(
    resolve(packageRoot, "node_modules/.bin/tailwindcss"),
    ["-i", "src/client/settings.css", "-o", builtPath, "--minify"],
    { cwd: packageRoot, stdio: "inherit" },
  );
  const compiled = scopeToSettings(unwrapLayers(readFileSync(builtPath, "utf8")));
  writeFileSync(
    outputPath,
    `// Generated by scripts/compile-settings-styles.mjs. Do not edit.\nexport const settingsStyles = ${JSON.stringify(compiled)};\n`,
  );
} finally {
  rmSync(builtDir, { recursive: true, force: true });
}

execFileSync(resolve(packageRoot, "node_modules/.bin/oxfmt"), ["--write", outputPath], {
  cwd: packageRoot,
  stdio: "inherit",
});

if (check && readFileSync(outputPath, "utf8") !== previous) {
  console.error("src/client/settings.generated.ts does not match the Tailwind build.");
  process.exit(1);
}
